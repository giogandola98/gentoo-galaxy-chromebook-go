#!/bin/bash
# SASUKE builder - commands run inside the container.
#   builder daemon   stay up (compose service); use "docker compose exec builder builder <cmd>"
#   builder update   sync repos and rebuild whatever changed (@world + kernel if needed)
#   builder world    @world only, no sync
#   builder kernel   build the kernel version in /etc/sasuke/KERNEL_VERSION ("force" to rebuild)
#   builder cpu      regenerate /etc/portage/cpu.conf for this machine's CPU
#   builder sign     sign every package not signed yet (after enabling signing)
#   builder status   tail of the log
set -o pipefail
LOG=/usr/src/build/builder.log
KV=$(cat /etc/sasuke/KERNEL_VERSION)
KOUT=/usr/src/build/out
log() { echo "[$(date '+%F %T')] $*" | tee -a "$LOG"; }

# --- Compiler flags -----------------------------------------------------------------
# The Celeron N4500 is "tremont". Freshly built programs also run during the build
# (configure checks, tests, generators), so every tremont ISA extension the builder CPU
# lacks is disabled. gcc option -> /proc/cpuinfo flag.
TREMONT_ISA="cldemote:cldemote clflushopt:clflushopt clwb:clwb gfni:gfni movbe:movbe
movdir64b:movdir64b movdiri:movdiri prfchw:3dnowprefetch ptwrite:ptwrite rdpid:rdpid
rdseed:rdseed sgx:sgx sha:sha_ni waitpkg:waitpkg xsavec:xsavec xsaves:xsaves
aes:aes pclmul:pclmulqdq popcnt:popcnt sse4.2:sse4_2 sse4.1:sse4_1 ssse3:ssse3
fsgsbase:fsgsbase rdrnd:rdrand xsave:xsave xsaveopt:xsaveopt"
cpu() {
  local have no="" o f
  have=" $(grep -m1 '^flags' /proc/cpuinfo | cut -d: -f2) "
  for p in $TREMONT_ISA; do
    o=${p%%:*}; f=${p#*:}
    [[ $have == *" $f "* ]] || no+=" -mno-$o"
  done
  local cores mem jobs
  cores=$(nproc)
  mem=$(awk '/MemTotal/ {print int($2/1048576)}' /proc/meminfo)
  jobs=$(( cores < mem/2 ? cores : mem/2 )); (( jobs < 1 )) && jobs=1
  [[ -n $BUILD_JOBS ]] && jobs=$BUILD_JOBS        # override (e.g. use every core)
  local extra=""
  [[ $ULTRA == 1 ]] && extra=" -flto=auto"
  cat > /etc/portage/cpu.conf <<EOF
# generated by "builder cpu" on $(date '+%F') for:$(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2-)
COMMON_FLAGS="-O2 -pipe -march=tremont -mtune=tremont${no}${extra}"
MAKEOPTS="-j${jobs} -l$((cores+1))"
PORTAGE_NICENESS="${BUILD_NICE:-15}"
EOF
  # ULTRA variant: global LTO, PGO where available (Firefox, Python, ...)
  [[ $ULTRA == 1 ]] && printf '%s\n' 'LDFLAGS="${LDFLAGS} -flto=auto"' 'USE="${USE} lto pgo"' >> /etc/portage/cpu.conf
  signing
  log "cpu.conf: -march=tremont${no:- (full)}${extra} | -j${jobs}${ULTRA:+ | ULTRA}"
}

# --- Package signing ------------------------------------------------------------------
# Every binary package is GPG-signed; the Chromebook trusts only this key (and Gentoo's).
# The private key lives in the build volume (not published); the public key is served
# by the binhost as sasuke-signing.asc.
GNUPGHOME_SIGN=/usr/src/build/gnupg
signing() {
  mkdir -p /run/lock            # gpg-keepalive lock (not present in a container)
  if [[ ! -f $GNUPGHOME_SIGN/fpr ]]; then
    install -d -m 700 "$GNUPGHOME_SIGN"
    gpg --homedir "$GNUPGHOME_SIGN" --batch --passphrase '' \
      --quick-gen-key "SASUKE builder (binary packages) <sasuke-builder@localhost>" ed25519 sign never
    gpg --homedir "$GNUPGHOME_SIGN" --list-secret-keys --with-colons | awk -F: '/^fpr/ {print $10; exit}' > "$GNUPGHOME_SIGN/fpr"
    log "signing key created: $(cat "$GNUPGHOME_SIGN/fpr")"
  fi
  gpg --homedir "$GNUPGHOME_SIGN" --armor --export "$(cat "$GNUPGHOME_SIGN/fpr")" > /var/cache/binpkgs/sasuke-signing.asc
  # Portage also verifies signed packages here (e.g. when reindexing): trust our own key
  local V=/etc/portage/gnupg
  [[ -f $V/pass ]] || getuto >/dev/null 2>&1
  if ! gpg --homedir "$V" --list-keys "$(cat "$GNUPGHOME_SIGN/fpr")" >/dev/null 2>&1; then
    gpg --homedir "$V" --batch --import /var/cache/binpkgs/sasuke-signing.asc 2>/dev/null
    gpg --homedir "$V" --batch --yes --pinentry-mode loopback --passphrase-file "$V/pass" \
      --quick-lsign-key "$(cat "$GNUPGHOME_SIGN/fpr")" 2>/dev/null
  fi
  cat > /etc/portage/signing.conf <<EOF
# generated by "builder cpu": sign every binary package
FEATURES="\${FEATURES} binpkg-signing gpg-keepalive"
BINPKG_GPG_SIGNING_GPG_HOME="$GNUPGHOME_SIGN"
BINPKG_GPG_SIGNING_KEY="0x$(cat "$GNUPGHOME_SIGN/fpr")"
EOF
}

# sign packages built before signing was enabled, then refresh the index
sign_all() {
  local n=0 f
  while IFS= read -r f; do
    gpkg-sign --skip-signed --allow-unsigned "$f" >/dev/null 2>&1 && n=$((n+1))
  done < <(find /var/cache/binpkgs -name '*.gpkg.tar')
  emaint binhost -f >/dev/null
  log "signed packages checked: $n"
}

# LTO breaks a few packages: rebuild those without LTO (remembered in package.env/no-lto)
no_lto_retry() {
  local failed a
  failed=$(sed -n '/The following packages have failed/,/^$/p' "$LOG" | grep -oE '[a-z0-9-]+/[A-Za-z0-9_+-]+-[0-9][^ :,]*' | sed -E 's/-[0-9].*$//' | sort -u)
  [[ -z $failed ]] && return 1
  log "rebuilding without LTO: $(echo $failed)"
  printf '%s\n' 'CFLAGS="${CFLAGS/-flto=auto/}"' 'CXXFLAGS="${CXXFLAGS/-flto=auto/}"' 'LDFLAGS="${LDFLAGS/-flto=auto/}"' 'USE="${USE} -lto"' > /etc/portage/env/no-lto.conf
  for a in $failed; do grep -q "^$a " /etc/portage/package.env/no-lto 2>/dev/null || echo "$a no-lto.conf" >> /etc/portage/package.env/no-lto; done
}

sync() {
  log "syncing repositories"
  emaint sync -a 2>&1 | tail -5 | tee -a "$LOG"
}

# First ULTRA run on a fresh stage3: clang/lld for the kernel, and break the
# docutils -> pillow -> harfbuzz -> glib -> docutils cycle (pillow without truetype once).
ultra_bootstrap() {
  [[ $ULTRA == 1 && ! -f /var/lib/sasuke-ultra-bootstrap ]] || return 0
  log "ULTRA bootstrap: pillow -truetype, clang, lld"
  USE="-truetype" emerge -1q --buildpkg=n dev-python/pillow 2>&1 | tail -3 | tee -a "$LOG"
  emerge -q --usepkg --buildpkg --noreplace llvm-core/clang llvm-core/lld 2>&1 | tail -3 | tee -a "$LOG" &&
    touch /var/lib/sasuke-ultra-bootstrap
}

world() {
  ultra_bootstrap
  log "emerge @world (reuses existing binaries, builds only what is new)"
  emerge --usepkg --buildpkg -uDNq --with-bdeps=y --keep-going @world 2>&1 | tee -a "$LOG" | grep -E '^(>>> Emerging|!!!| \* ERROR)'
  local rc=$?
  if [[ $ULTRA == 1 && $rc -ne 0 ]] && no_lto_retry; then
    emerge --usepkg --buildpkg -uDNq --with-bdeps=y --keep-going @world 2>&1 | tee -a "$LOG" | grep -E '^(>>> Emerging|!!!| \* ERROR)'
    rc=$?
  fi
  emerge --depclean -q 2>&1 | tail -2
  log "world done (rc=$rc)"
}

kernel() {
  local src=/usr/src/linux-${KV}-gentoo
  local art=/var/cache/binpkgs/sasuke-kernel
  if [[ -f $art/kernel-${KV}-sasuke.tar.zst && $art/kernel-${KV}-sasuke.tar.zst -nt /etc/sasuke/kernel.config && $1 != force ]]; then
    log "kernel ${KV} already built"; return 0
  fi
  log "kernel ${KV}: sources"
  [[ -d $src ]] || emerge -1q --usepkg=n "=sys-kernel/gentoo-sources-${KV}" || return 1
  mkdir -p "$KOUT" "$art"
  cp /etc/sasuke/kernel.config "$KOUT/.config"
  local M="make -C $src O=$KOUT KCFLAGS=-march=tremont $(. /etc/portage/cpu.conf; echo "$MAKEOPTS")"
  if [[ $ULTRA == 1 ]]; then   # clang + full LTO kernel (our kernel is small, so full LTO fits in RAM)
    M="$M LLVM=1"
    $M olddefconfig >/dev/null
    "$src"/scripts/config --file "$KOUT/.config" -d LTO_NONE -d LTO_CLANG_THIN -e LTO_CLANG_FULL
  fi
  log "kernel ${KV}: compiling"
  $M olddefconfig >/dev/null && $M bzImage modules 2>&1 | tail -3 | tee -a "$LOG" || return 1
  local st; st=$(mktemp -d)
  $M INSTALL_MOD_PATH="$st" INSTALL_MOD_STRIP=1 modules_install >/dev/null || return 1
  mkdir -p "$st/boot"
  cp "$KOUT/arch/x86/boot/bzImage" "$st/boot/vmlinuz-${KV}-gentoo-sasuke"
  cp "$KOUT/.config" "$st/boot/config-${KV}-gentoo-sasuke"
  cp "$KOUT/System.map" "$st/boot/System.map-${KV}-gentoo-sasuke"
  log "kernel ${KV}: v4l2loopback"
  KERNEL_DIR=$src KBUILD_OUTPUT=$KOUT emerge -1q --usepkg=n media-video/v4l2loopback 2>&1 | tail -2
  # pack only boot/ and lib/ (never the "." entry: it would change permissions of / on the Chromebook)
  tar -C "$st" --zstd -cf "$art/kernel-${KV}-sasuke.tar.zst" boot lib &&
    (cd "$art" && sha256sum "kernel-${KV}-sasuke.tar.zst" > "kernel-${KV}-sasuke.tar.zst.sha256") &&
    echo "${KV}" > "$art/LATEST"
  rm -rf "$st"
  log "kernel ${KV}: ready in sasuke-kernel/"
}

case "$1" in
  daemon) cpu; log "builder ready"; exec sleep infinity ;;
  cpu)    cpu ;;
  sync)   sync ;;
  world)  cpu; world ;;
  kernel) cpu; kernel "$2" ;;
  update) cpu; sync; world; kernel; log "UPDATE_DONE" ;;
  sign)   cpu; sign_all ;;
  status) tail -n "${2:-20}" "$LOG" ;;
  shell)  exec bash ;;
  *) sed -n '2,9p' "$0" ;;
esac
